namespace Nekolpos.System
{
    /// <summary>
    /// 【ステートパターン用インターフェース】
    /// ゲームの各状態（朝、昼、夜、死亡など）を管理するための設計図です。
    /// 後々新しい状態（例：「祭りイベント状態」など）を追加したくなった場合、
    /// このインターフェースを継承した新しいクラスを作るだけで、既存のシステムを壊さずに拡張できます。
    /// </summary>
    public interface IGameState
    {
        /// <summary>
        /// そのフェーズ（状態）に突入した瞬間に1回だけ実行される処理です。
        /// 例：画面の明るさを変える、BGMを再生する、朝専用の会話をセットするなど。
        /// </summary>
        void Enter();

        /// <summary>
        /// そのフェーズ中、毎フレーム（Update）呼ばれ続ける処理です。
        /// 例：プレイヤーの入力を監視する、時間を進めるなど。
        /// </summary>
        void Execute();

        /// <summary>
        /// 別のフェーズに切り替わる瞬間、最後に1回だけ実行される処理です。
        /// 例：一時変数をリセットする、UIを閉じるなど。
        /// </summary>
        void Exit();
    }
}
